def runtime_lock():
    """Bind the interpreter and every installed distribution's static bytes.

    Generated bytecode is excluded because imports may create it. All other
    files listed by distribution metadata are hashed from the installation,
    including native extensions and metadata. Extra packages are disclosed;
    extraction lock pins must be present exactly, with no optional fallback.
    """
    import peps
    try:
        import trafilatura
        import lxml.etree as etree
    except ImportError as exc:
        raise ValueError('La corrida requiere trafilatura y lxml instalados; no se admite fallback ausente.') from exc
    lock_path = ROOT / 'requirements-extraction.lock.txt'
    required = {}
    for raw in lock_path.read_text(encoding='utf-8').splitlines():
        line = raw.partition('#')[0].strip()
        if not line:
            continue
        requirement, separator, marker = line.partition(';')
        if separator:
            if marker.strip() != 'platform_system == "Windows"':
                raise ValueError('Marcador de dependencia no reconocido en el lock de extracción.')
            if platform.system() != 'Windows':
                continue
        match = re.fullmatch(r'([A-Za-z0-9_.-]+)==([^\s;]+)', requirement.strip())
        if not match:
            raise ValueError('El lock de extracción requiere versiones exactas sin instaladores dinámicos.')
        name, version = match.groups()
        try:
            installed = importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError as exc:
            raise ValueError('Falta la dependencia congelada: ' + name) from exc
        if installed != version:
            raise ValueError('Versión distinta del lock de extracción: ' + name + ' ' + installed + ' != ' + version)
        required[name] = version
    packages, seen_distributions = [], set()
    for distribution in sorted(importlib.metadata.distributions(), key=lambda value: (value.metadata.get('Name', '').casefold(), value.version)):
        location = str(Path(distribution.locate_file('')).resolve())
        key = (distribution.metadata.get('Name'), distribution.version, location)
        if key in seen_distributions:
            continue  # Helper imports may put the same project path on sys.path more than once.
        seen_distributions.add(key)
        manifest = []
        for relative in sorted(distribution.files or [], key=str):
            if str(relative).endswith(('.pyc', '.pyo')) or '__pycache__' in relative.parts:
                continue
            installed_path = Path(distribution.locate_file(relative))
            manifest.append({'path': str(relative), 'sha256': file_hash(installed_path)} if installed_path.is_file()
                            else {'path': str(relative), 'missing': True})
        packages.append({'name': distribution.metadata.get('Name'), 'version': distribution.version, 'installation_root': location,
                         'static_file_count': len(manifest), 'static_file_manifest_sha256': digest(canonical(manifest)),
                         'missing_static_files': [row['path'] for row in manifest if row.get('missing')]})
    return {'python_executable': sys.executable, 'python_real_executable': str(Path(sys.executable).resolve()),
        'python_executable_sha256': file_hash(Path(sys.executable).resolve()),
        'python_version': sys.version, 'python_implementation': sys.implementation.name,
        'python_cache_tag': sys.implementation.cache_tag, 'python_prefix': sys.prefix,
        'python_base_prefix': sys.base_prefix, 'python_optimization': sys.flags.optimize,
        'platform': platform.platform(), 'sqlite_version': sqlite3.sqlite_version,
        'peps_import_path': str(Path(peps.__file__).resolve()), 'peps_source_version': peps.__version__,
        'trafilatura_import_path': str(Path(trafilatura.__file__).resolve()),
        'trafilatura_version': importlib.metadata.version('trafilatura'),
        'lxml_version': importlib.metadata.version('lxml'),
        'lxml_native_extension_sha256': file_hash(etree.__file__),
        'libxml_version': list(etree.LIBXML_VERSION), 'libxslt_version': list(etree.LIBXSLT_VERSION),
        'required_extraction_pins': required, 'installed_distributions': packages,
        'distribution_manifest_scope': 'All installed distribution metadata-listed static files, including harmless extra packages; generated bytecode excluded.'}


def assert_new_paths(args):
    bank, archive = args.data_dir.resolve(), args.closed_bank.resolve()
    inputs = [args.roster.resolve(), args.sources_config.resolve(), args.protocol_lock.resolve()]
    if args.utility_lock:
        inputs.append(args.utility_lock.resolve())
    if args.roster_sanitization_lock:
        inputs.append(args.roster_sanitization_lock.resolve())
    if args.census_policy_lock:
        inputs.append(args.census_policy_lock.resolve())
    if args.host_policy_registry:
        inputs.append(args.host_policy_registry.resolve())
    if args.host_policy_importer:
        inputs.append(args.host_policy_importer.resolve())
    if getattr(args, 'api_transport_lock', None):
        inputs.append(args.api_transport_lock.resolve())
    if getattr(args, 'query_input_lock', None):
        inputs.append(args.query_input_lock.resolve())
    outputs = [args.output.resolve(), args.close_receipt.resolve(), args.api_export.resolve()]
    all_files = inputs + outputs + [args.launch_lock.resolve()]
    if bank == archive or bank in archive.parents or archive in bank.parents:
        raise ValueError('El banco frío y el banco de cierre deben ser directorios distintos, sin anidarse.')
    for directory in (bank, archive):
        if directory.exists():
            raise ValueError('El banco frío y el cierre requieren rutas nuevas, nunca un banco reutilizado: ' + str(directory))
        if any(path == directory or directory in path.parents for path in all_files):
            raise ValueError('Insumos, locks y resultados deben quedar fuera de los bancos.')
    if len(set(outputs + [args.launch_lock.resolve()])) != 4 or set(inputs) & set(outputs):
        raise ValueError('Las salidas y el lock deben tener rutas únicas y no reemplazar insumos.')
    for path in outputs:
        if path.exists():
            raise ValueError('La salida ya existe; se conserva sin sobrescribir: ' + str(path))


