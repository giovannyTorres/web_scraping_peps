def freeze(args):
    assert_new_paths(args)
    lock = expected_lock(args)
    lock['started_at'] = now()
    lock['meaning_started_at'] = 'Prelaunch input freeze; measured acquisition starts in production phase journal.'
    write_new_json(args.launch_lock, lock)
    return lock


def validate_launch(args):
    if not args.online or not args.root_go:
        raise ValueError('La ejecución real requiere --online y --root-go tras congelar la configuración.')
    assert_new_paths(args)
    recorded = json.loads(args.launch_lock.read_text(encoding='utf-8'))
    current = expected_lock(args)
    comparison = {key: value for key, value in recorded.items() if key not in ('started_at', 'meaning_started_at')}
    if comparison != current:
        raise ValueError('Cambió el padrón, catálogo, plan, código, protocolo, rutas o presupuesto desde el lock. Cree otro lock antes de ejecutar.')
    if not isinstance(recorded.get('started_at'), str):
        raise ValueError('El lock no conserva el instante anterior a la adquisición.')
    return recorded


def database_fingerprints(path):
    """Hash every logical row in a read snapshot; SQLite backup bytes may differ."""
    result = {}
    with closing(sqlite3.connect(Path(path).resolve().as_uri() + '?mode=ro', uri=True)) as con:
        con.row_factory = sqlite3.Row
        con.execute('BEGIN')
        names = [row[0] for row in con.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")]
        for name in names:
            quoted = '"' + name.replace('"', '""') + '"'
            columns = [row[1] for row in con.execute('PRAGMA table_info(' + quoted + ')')]
            ordering = ','.join('"' + column.replace('"', '""') + '"' for column in columns)
            state, count = hashlib.sha256(), 0
            for row in con.execute('SELECT * FROM ' + quoted + ' ORDER BY ' + ordering):
                values = [(key, {'sqlite_blob_hex': value.hex()} if isinstance(value, bytes) else value) for key, value in dict(row).items()]
                encoded = canonical(values).encode('utf-8')
                state.update(len(encoded).to_bytes(8, 'big'))
                state.update(encoded)
                count += 1
            result[name] = {'rows': count, 'sha256': state.hexdigest()}
    return result


def close_sqlite_bank(directory):
    """Publish standalone SQLite backups after all localhost handlers stopped."""
    receipts = {}
    for name in ('peps.sqlite3', 'network.sqlite3'):
        original = directory / name
        if not original.exists():
            continue
        temporary = original.with_name(original.name + '.closed-backup')
        if temporary.exists():
            raise ValueError('Ya existe un backup temporal, no se reemplaza: ' + str(temporary))
        with closing(sqlite3.connect(original.resolve().as_uri() + '?mode=ro', uri=True)) as source:
            with closing(sqlite3.connect(temporary)) as target:
                source.backup(target)
                quick_check = target.execute('PRAGMA quick_check').fetchone()[0]
        if quick_check != 'ok':
            raise ValueError('Falló quick_check del backup de cierre: ' + name)
        # No live SQLite connections or request workers remain at this point.
        for suffix in ('-wal', '-shm'):
            original.with_name(name + suffix).unlink(missing_ok=True)
        temporary.replace(original)
        receipts[name] = {'sha256': file_hash(original), 'bytes': original.stat().st_size,
                          'quick_check': quick_check}
    return receipts


def get_explanation(server_port, token, entity_id, run_id, captures, index, timeout):
    """One genuine loopback GET, with raw response persisted before decoding."""
    path = '/api/explanation?' + urlencode({'id': entity_id, 'run_id': run_id})
    began = time.monotonic()
    record = {'entity_id': entity_id, 'run_id': run_id, 'method': 'GET',
              'host': '127.0.0.1', 'path': path, 'started_at': now()}
    connection = http.client.HTTPConnection('127.0.0.1', server_port, timeout=timeout)
    try:
        connection.request('GET', path, headers={'X-PEPS-Token': token, 'Accept': 'application/json'})
        response = connection.getresponse()
        body = response.read(16 * 1024 * 1024 + 1)
        if len(body) > 16 * 1024 * 1024:
            raise ValueError('La respuesta individual supera el límite explícito de 16 MiB.')
        capture = captures / f'{index:04d}-{hashlib.sha256(body).hexdigest()}.json'
        capture.write_bytes(body)
        record.update(http_status=response.status, response_bytes=len(body),
                      response_sha256=hashlib.sha256(body).hexdigest(), capture_path=str(capture))
        payload = json.loads(body)
        if response.status != 200:
            raise ValueError('La API devolvió HTTP ' + str(response.status) + ': ' + str(payload.get('error', '')))
        if (payload.get('entity', {}).get('id') != entity_id or payload.get('run', {}).get('id') != run_id
                or not isinstance(payload.get('document_review'), dict)):
            raise ValueError('La respuesta no corresponde a la entidad/run o falta document_review de producción.')
        record['ok'] = True
        return payload, record
    except Exception as exc:
        record.update(ok=False, error_type=type(exc).__name__, error=str(exc))
        return None, record
    finally:
        record['seconds'] = time.monotonic() - began
        connection.close()


def get_explanation_batch(server_port, token, rows, captures, index, timeout):
    """A genuine bounded production POST; retain its complete raw envelope."""
    path = '/api/explanations'
    began = time.monotonic()
    record = {'entity_ids': [row['entity_id'] for row in rows],
              'run_ids': [row['run_id'] for row in rows], 'method': 'POST',
              'host': '127.0.0.1', 'path': path, 'started_at': now()}
    connection = http.client.HTTPConnection('127.0.0.1', server_port, timeout=timeout)
    try:
        body = canonical({'run_ids': record['run_ids']}).encode('utf-8')
        connection.request('POST', path, body=body, headers={
            'X-PEPS-Token': token, 'Accept': 'application/json', 'Content-Type': 'application/json'})
        response = connection.getresponse()
        raw = response.read(64 * 1024 * 1024 + 1)
        if len(raw) > 64 * 1024 * 1024:
            raise ValueError('La respuesta del lote supera el límite explícito de 64 MiB.')
        capture = captures / f'{index:04d}-{hashlib.sha256(raw).hexdigest()}.json'
        capture.write_bytes(raw)
        record.update(http_status=response.status, response_bytes=len(raw),
                      response_sha256=hashlib.sha256(raw).hexdigest(), capture_path=str(capture))
        envelope = json.loads(raw)
        if response.status != 200:
            raise ValueError('La API devolvió HTTP ' + str(response.status) + ': ' + str(envelope.get('error', '')))
        payloads = envelope.get('items')
        if (not isinstance(payloads, list) or len(payloads) != len(rows)
                or any(payload.get('entity', {}).get('id') != row['entity_id']
                       or payload.get('run', {}).get('id') != row['run_id']
                       or not isinstance(payload.get('document_review'), dict)
                       for row, payload in zip(rows, payloads))):
            raise ValueError('El lote no corresponde exactamente a las entidades/evaluaciones solicitadas.')
        record.update(ok=True, payload_count=len(payloads))
        return payloads, record
    except Exception as exc:
        record.update(ok=False, error_type=type(exc).__name__, error=str(exc))
        return [], record
    finally:
        record['seconds'] = time.monotonic() - began
        connection.close()


def export_actual_api(source_bank, closed_bank, destination, *, workers=4, timeout=120, batch_size=1):
    """Serve an independent exact copy, then close that same evaluated bank.

    create_server initializes ordinary workflow tables. Those explicit auxiliary
    changes belong to this copy; its default catalogue merge is disabled;
    original acquisition bank and its frozen catalogue stay untouched. Every
    score, evidence item, body, audit row, job and identity must remain exact.
    """
    if type(batch_size) is not int or not 1 <= batch_size <= 50:
        raise ValueError('El lote HTTP requiere de 1 a 50 evaluaciones.')
    source_before = database_fingerprints(source_bank / 'peps.sqlite3')
    source_config_before = file_hash(source_bank / 'news_sources.json')
    source_network_before = database_fingerprints(source_bank / 'network.sqlite3') if (source_bank / 'network.sqlite3').exists() else {}
    copy_bank(source_bank, closed_bank)
    copied_before = database_fingerprints(closed_bank / 'peps.sqlite3')
    engine = Engine(closed_bank, online=False)
    server, token = create_server(engine, merge_source_defaults=False)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    captures = destination.with_name(destination.stem + '-responses-private')
    captures.mkdir(parents=True, exist_ok=False)
    responses, events = [], []
    began = time.monotonic()
    with engine.store.connection() as con:
        runs = [dict(row) for row in con.execute('SELECT entity_id,run_id FROM scores ORDER BY entity_id')]
    try:
        with ThreadPoolExecutor(max_workers=workers) as pool:
            if batch_size == 1:
                futures = [pool.submit(get_explanation, server.server_port, token, row['entity_id'], row['run_id'], captures, index, timeout)
                           for index, row in enumerate(runs)]
            else:
                futures = [pool.submit(get_explanation_batch, server.server_port, token, runs[offset:offset + batch_size], captures, index, timeout)
                           for index, offset in enumerate(range(0, len(runs), batch_size))]
            for future in as_completed(futures):
                payload, event = future.result()
                events.append(event)
                if payload is not None:
                    responses.extend(payload if batch_size > 1 else [payload])
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=10)
    api_seconds = time.monotonic() - began
    copied_after = database_fingerprints(closed_bank / 'peps.sqlite3')
    source_after = database_fingerprints(source_bank / 'peps.sqlite3')
    confirmations = 0
    with engine.store.connection() as con:
        confirmations = sum(json.loads(row[0] or '{}').get('status') == 'confirmed' for row in con.execute('SELECT review FROM evidence'))
    checks = {'initial_copy_all_logical_tables_exact': copied_before == source_before,
        'all_core_rows_unchanged_by_api': all(copied_after.get(table) == copied_before.get(table) for table in READ_ONLY_CORE),
        'original_bank_all_logical_tables_unchanged': source_before == source_after,
        'original_frozen_catalogue_bytes_unchanged': file_hash(source_bank / 'news_sources.json') == source_config_before,
        'original_http_cache_and_history_unchanged': source_network_before == (database_fingerprints(source_bank / 'network.sqlite3') if source_network_before else {}),
        'closed_copy_http_cache_and_history_unchanged': source_network_before == (database_fingerprints(closed_bank / 'network.sqlite3') if source_network_before else {}),
        'closed_copy_frozen_catalogue_bytes_unchanged': file_hash(closed_bank / 'news_sources.json') == source_config_before,
        'no_automatic_human_review_confirmations': confirmations == 0,
        'all_actual_api_responses_successful': len(responses) == len(runs) and all(event['ok'] for event in events),
        'exact_entity_ids_and_run_ids': {(value['entity']['id'], value['run']['id']) for value in responses}
            == {(row['entity_id'], row['run_id']) for row in runs} and len(responses) == len(runs),
        'api_documentary_cards_do_not_create_identity_confirmations': all(value['document_review'].get('identity_confirmations_created') == 0 for value in responses),
        'all_core_source_tables_exist': all(table in copied_before for table in READ_ONLY_CORE),
        'api_thread_stopped': not thread.is_alive()}
    if batch_size == 1:
        checks['one_actual_get_per_scored_entity'] = len(events) == len(runs) and all(event['method'] == 'GET' for event in events)
    else:
        requested = [(entity, run) for event in events for entity, run in zip(event['entity_ids'], event['run_ids'])]
        checks['one_actual_http_batch_membership_per_scored_entity'] = (
            len(events) == math.ceil(len(runs) / batch_size)
            and len(requested) == len(set(requested)) == len(runs)
            and set(requested) == {(row['entity_id'], row['run_id']) for row in runs}
            and all(event['method'] == 'POST' and len(event['run_ids']) <= batch_size for event in events))
    backups = close_sqlite_bank(closed_bank)
    checks['backup_logical_tables_match_final_api_bank'] = database_fingerprints(closed_bank / 'peps.sqlite3') == copied_after
    output = {'schema_version': SCHEMA_VERSION, 'method': 'production_explanation_api',
        'generated_at': now(), 'bank_sha256': backups['peps.sqlite3']['sha256'],
        'bank_dir': str(closed_bank), 'source_bank_dir': str(source_bank),
        'api_transport': 'Authenticated HTTP ' + ('GET' if batch_size == 1 else 'POST batch') + ' to production create_server bound to 127.0.0.1; explicit historical run IDs prevent implicit scoring.',
        'api_batch_size': batch_size, 'actual_http_requests': len(events), 'actual_explanation_payloads': len(responses),
        'actual_successful_http_batches': sum(event['ok'] for event in events) if batch_size > 1 else 0,
        'unique_entity_ids': len({value['entity']['id'] for value in responses}),
        'unique_run_ids': len({value['run']['id'] for value in responses}),
        'public_web_requests_during_api_export': 0, 'seconds': api_seconds,
        'responses': sorted(responses, key=lambda value: value['entity']['id']),
        'http_events': sorted(events, key=lambda value: value.get('entity_id') or value['entity_ids'][0]),
        'source_table_fingerprints': source_before, 'closed_table_fingerprints': copied_after,
        'auxiliary_table_changes': {table: {'before': copied_before.get(table), 'after': copied_after.get(table)}
            for table in sorted(set(copied_before) | set(copied_after)) if copied_before.get(table) != copied_after.get(table)},
        'closed_catalogue_sha256': file_hash(closed_bank / 'news_sources.json'),
        'source_catalogue_sha256': source_config_before, 'sqlite_backups': backups,
        'checks': checks, 'passed': all(checks.values()), 'human_confirmations': confirmations,
        'individual_payloads_and_article_quotes_are_private': True}
    write_new_json(destination, output)
    return output


def successful_searched_people(report):
    """Require a parsed durable nominal query and an actual successful HTTP."""
    successful = {request_key(event.get('parent_fetch_url') or event['url'])
                  for event in report['session_http_events']
                  if not event.get('robots_request') and type(event.get('http_status')) is int
                  and 200 <= event['http_status'] < 300}
    return {identifier for query in report['query_results']
            if query['discovery_receipt_saved'] and query['status'] == 'done'
            and request_key(query['query_url']) in successful
            for identifier in query['entity_ids']}


def acquisition_finished_at(report):
    path = Path(report['run']['attempt_dir']) / 'phases.jsonl'
    for line in path.read_text(encoding='utf-8').splitlines():
        row = json.loads(line)
        if row.get('phase') == 'search_and_original_download' and row.get('event') == 'finished':
            return row['at']
    return None


def import_negative_host_policy(engine, config, attempt, frozen):
    """Initialize empty network tables, then run the exact frozen audit helper.

    SafeFetcher is offline and never asked to fetch. The helper can only carry
    host restrictions forward; its original receipt and zero-content initial
    counts remain inspectable beside the transport journals.
    """
    if (file_hash(frozen['registry_path']) != frozen['registry_sha256']
            or file_hash(frozen['importer_path']) != frozen['importer_sha256']):
        raise ValueError('Registry o importer cambiaron después de congelar la corrida.')
    network = engine.data_dir / 'network.sqlite3'
    if network.exists():
        raise ValueError('La importación negativa requiere una base de red recién inicializada, sin estado anterior.')
    fetcher = SafeFetcher(config, engine.data_dir, offline=True)
    fetcher.close()
    empty_tables = ('http_cache', 'robots', 'robots_refresh', 'redirects', 'request_history')
    with closing(sqlite3.connect(network.resolve().as_uri() + '?mode=ro', uri=True)) as con:
        before = {name: con.execute('SELECT count(*) FROM ' + name).fetchone()[0] for name in (*empty_tables, 'hosts')}
    with engine.store.connection() as con:
        initial_bank = {name: con.execute('SELECT count(*) FROM ' + name).fetchone()[0]
                        for name in ('entities', 'documents', 'scores', 'score_runs', 'news_articles', 'news_observations')}
    if any(before.values()) or any(initial_bank.values()):
        raise ValueError('El banco inicial contiene contenido, consultas o entidades; no se puede tratar como frío.')
    initial_path = attempt / 'network-policy-initial-empty-receipt.json'
    write_new_json(initial_path, {'at': now(), 'network_table_counts': before, 'bank_table_counts': initial_bank,
        'network_requests': 0, 'registry_sha256': frozen['registry_sha256'],
        'importer_sha256': frozen['importer_sha256']})
    receipt_path = attempt / 'negative-host-policy-import-receipt.json'
    command = [sys.executable, frozen['importer_path'], '--network-db', str(network),
               '--registry', frozen['registry_path'], '--registry-sha256', frozen['registry_sha256'],
               '--receipt', str(receipt_path)]
    result = subprocess.run(command, capture_output=True, text=True, timeout=30, check=False)
    (attempt / 'negative-host-policy-import.stdout').write_text(result.stdout, encoding='utf-8')
    (attempt / 'negative-host-policy-import.stderr').write_text(result.stderr, encoding='utf-8')
    if result.returncode != 0 or not receipt_path.is_file():
        raise ValueError('Falló el importer congelado; sus mensajes se conservaron en el intento, sin iniciar HTTP.')
    receipt = json.loads(receipt_path.read_text(encoding='utf-8'))
    with closing(sqlite3.connect(network.resolve().as_uri() + '?mode=ro', uri=True)) as con:
        after = {name: con.execute('SELECT count(*) FROM ' + name).fetchone()[0] for name in empty_tables}
        policy_hosts = con.execute('SELECT count(*) FROM hosts').fetchone()[0]
        host_counters_empty = con.execute('SELECT count(*) FROM hosts WHERE failures!=0 OR last_at!=0').fetchone()[0] == 0
    with engine.store.connection() as con:
        after_bank = {name: con.execute('SELECT count(*) FROM ' + name).fetchone()[0] for name in initial_bank}
    if (any(after.values()) or receipt.get('registry_sha256') != frozen['registry_sha256']
            or receipt.get('network_requests') != 0 or receipt.get('content_counts_remain_zero') is not True
            or receipt.get('existing_restrictions_only_strengthened') is not True
            or after_bank != initial_bank or not host_counters_empty):
        raise ValueError('El importer no conservó las tablas de contenido vacías y las restricciones monotónicas.')
    outcome = {'initial_empty_receipt_path': str(initial_path), 'initial_empty_receipt_sha256': file_hash(initial_path),
        'import_receipt_path': str(receipt_path), 'import_receipt_sha256': file_hash(receipt_path),
        'registry_sha256': frozen['registry_sha256'], 'importer_sha256': frozen['importer_sha256'],
        'imported_policy_host_rows': policy_hosts, 'content_counts_after': after,
        'bank_table_counts_after': after_bank, 'imported_host_failure_counters_empty': host_counters_empty,
        'network_requests': 0, 'receipt': receipt}
    engine.store.audit('cold_negative_host_policy_imported', outcome)
    return outcome


def run(args):
    launch = validate_launch(args)
    # Existing production runner captures real response bytes/status/errors and
    # maintains its original failed operational checks without reinterpretation.
    policy_receipt = None
    def initialize_policy(engine, config, attempt):
        nonlocal policy_receipt
        policy_receipt = import_negative_host_policy(engine, config, attempt, launch['negative_host_policy'])
    report = live.run(args, initialize_network_policy=initialize_policy if launch['negative_host_policy'] else None)
    api = export_actual_api(args.data_dir.resolve(), args.closed_bank.resolve(), args.api_export.resolve(),
                           workers=args.api_workers, timeout=args.api_timeout, batch_size=args.api_batch_size)
    searched = successful_searched_people(report)
    receipt = {'schema_version': SCHEMA_VERSION, 'launch_lock_sha256': file_hash(args.launch_lock),
        'protocol_sha256': launch['protocol_sha256'], 'closed_bank_dir': str(args.closed_bank.resolve()),
        'closed_bank_sha256': api['bank_sha256'], 'acquisition_finished_at': acquisition_finished_at(report),
        'finished_at': now(), 'acquisition_seconds': report['timings_seconds'].get('search_and_original_download'),
        'scoring_seconds': report['timings_seconds'].get('production_scoring'),
        'attribution_seconds': report['timings_seconds'].get('identity_attribution'),
        'explanation_api_seconds': api['seconds'], 'searched_entities_with_successful_real_http': len(searched),
        'successful_searched_entity_ids': sorted(searched),
        'actual_http_requests': report['summary']['actual_http_requests_this_session'],
        'production_replays_exact': report['phase_results'].get('replay', {}).get('matched', 0),
        'automated_human_confirmations': api['human_confirmations'],
        'actual_explanation_api_responses': len(api['responses']), 'explanation_api_export_sha256': file_hash(args.api_export),
        'explanation_api_http_requests': api['actual_http_requests'],
        'explanation_api_batch_size': api['api_batch_size'], 'explanation_api_transport': api['api_transport'],
        'explanation_api_contract': launch['api_export_contract'],
        'production_report_sha256': file_hash(args.output), 'source_hashes_after': source_hashes(),
        'source_modules_unchanged_since_launch': launch['source_hashes'] == source_hashes(),
        'runtime_after': runtime_lock(),
        'negative_host_policy_import': policy_receipt,
        'sqlite_backups': api['sqlite_backups'], 'operational_checks': report['operational_checks'],
        'api_checks': api['checks'], 'operational_passed': report['operational_passed'] and api['passed'],
        'independent_quality_gate_not_evaluated_here': True,
        'no_sufficiency_claim_from_completed_scores': True,
        'closed_copy_auxiliary_initialization': api['auxiliary_table_changes']}
    receipt['runtime_unchanged_since_launch'] = launch['runtime'] == receipt['runtime_after']
    write_new_json(args.close_receipt, receipt)
    print(json.dumps({'closed_bank': str(args.closed_bank.resolve()), 'close_receipt': str(args.close_receipt.resolve()),
        'people_searched_successfully': len(searched), 'articles': report['summary']['unique_original_documents'],
        'scores': report['summary']['production_scores_computed'], 'real_api_responses': len(api['responses']),
        'acquisition_seconds': receipt['acquisition_seconds'], 'scoring_seconds': receipt['scoring_seconds'],
        'operational_passed': receipt['operational_passed'], 'quality_gate_pending': True}, ensure_ascii=False), flush=True)
    return receipt


def parser():
    value = argparse.ArgumentParser(description=__doc__)
    for name in ('roster', 'sources-config', 'data-dir', 'output', 'closed-bank', 'protocol-lock',
                 'launch-lock', 'close-receipt', 'api-export'):
        value.add_argument('--' + name, type=Path, required=True)
    value.add_argument('--utility-lock', type=Path)
    value.add_argument('--census-policy-lock', type=Path,
                       help='Predeclared full-frame annotation extension policy, frozen before acquisition.')
    value.add_argument('--host-policy-registry', type=Path,
                       help='Pre-frozen negative host restrictions only, without cached content or successful queries.')
    value.add_argument('--host-policy-importer', type=Path,
                       help='Reviewed importer helper; exact code and registry hashes are locked before execution.')
    value.add_argument('--roster-sanitization-lock', type=Path,
                       help='Frozen correspondence receipt for the same 300 names after removing labels/reference URLs.')
    value.add_argument('--freeze-only', action='store_true', help='Write an immutable prelaunch lock without opening a bank or using the network.')
    value.add_argument('--online', action='store_true')
    value.add_argument('--root-go', action='store_true', help='Explicit operator launch switch after the final lock; never bypasses source access policy.')
    value.add_argument('--seconds', type=float, default=900)
    value.add_argument('--acquire-seconds', type=float, default=600)
    value.add_argument('--max-http', type=int, default=20000)
    value.add_argument('--workers', type=int, default=32)
    value.add_argument('--body-budget', type=int, default=2400)
    value.add_argument('--per-entity-body-limit', type=int, default=16)
    value.add_argument('--max-jobs', type=int, default=50000)
    value.add_argument('--api-workers', type=int, default=4)
    value.add_argument('--api-timeout', type=float, default=120)
    value.add_argument('--api-batch-size', type=int, default=1)
    value.add_argument('--api-transport-lock', type=Path,
                       help='Prelaunch transport addendum; mandatory for batches, without changing acceptance gates.')
    value.add_argument('--query-input-lock', type=Path,
                       help='Prospective input-rule addendum; mandatory for unquoted public-name search.')
    # A separate warm/cache experiment may be run later; it is never part of the
    # claimed empty-bank acquisition or silently counted toward cold coverage.
    value.set_defaults(resume=False, allow_small_roster=False, skip_local_validation=True, local_seconds=60)
    return value


def main():
    argument_parser = parser()
    args = argument_parser.parse_args()
    if (not math.isfinite(args.seconds) or not 0 < args.seconds <= 2400
            or not math.isfinite(args.acquire_seconds) or not 0 < args.acquire_seconds <= args.seconds
            or not 1 <= args.max_http <= 50000 or not 1 <= args.workers <= 32
            or not 1 <= args.body_budget <= 5000 or not 1 <= args.per_entity_body_limit <= 100
            or not 1 <= args.max_jobs <= 100000 or not 1 <= args.api_workers <= 8
            or not 1 <= args.api_batch_size <= 50
            or not math.isfinite(args.api_timeout) or not 0 < args.api_timeout <= 300):
        argument_parser.error('Presupuestos finitos: hasta 2400 s/50000 HTTP/32 workers; API localhost hasta 8 workers/300 s por GET.')
    try:
        if args.freeze_only:
            lock = freeze(args)
            print(json.dumps({'launch_lock': str(args.launch_lock.resolve()), 'launch_lock_sha256': file_hash(args.launch_lock),
                'people': lock['people'], 'queries': len(lock['nominal_plan']['queries']),
                'network_requests': 0, 'bank_opened': False, 'launch_authorized': False}, ensure_ascii=False), flush=True)
            return
        receipt = run(args)
    except (ValueError, OSError, json.JSONDecodeError) as exc:
        argument_parser.error(str(exc))
    if (not receipt['operational_passed'] or not receipt['source_modules_unchanged_since_launch']
            or not receipt['runtime_unchanged_since_launch']):
        raise SystemExit(1)


if __name__ == '__main__':
    main()
